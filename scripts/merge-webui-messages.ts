function merge(path: string, extra: Record<string, string>): void {
  const data = JSON.parse(readFileSync(path, "utf8")) as Record<string, string>;
  const merged = { ...data, ...extra };
  const keys = Object.keys(merged).toSorted();
  const sorted: Record<string, string> = {};
  for (const k of keys) sorted[k] = merged[k]!;
  writeFileSync(path, `${JSON.stringify(sorted, null, 2)}\n`);
}

